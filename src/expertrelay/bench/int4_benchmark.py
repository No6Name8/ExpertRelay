"""Speed of int8 vs int4 experts, same session, same settings.

    python -m expertrelay.bench.int4_benchmark --int4-store models/qwen1.5-moe-a2.7b-int4g64
    python -m expertrelay.bench.int4_benchmark --report

Phase 2 prompts and settings (base model, 32 new tokens, greedy), fused
kernel, 2 I/O threads, pipelined prefill. For each precision:

  nocache   one read per expert use, no cache (the reference for the
            token-identity check within this precision)
  cache     1.25 GB cache, no prediction
  adaptive  1.25 GB cache + adaptive prefetch (threshold 0.05)

Same cache size in GB for both precisions, so int4 (about half the bytes
per expert) holds about twice as many experts. The int4 runs use the base
int8 store's prefetch calibration (its routing traces); the run records
flag this (calibration_store_matches).

Every setup runs twice (second round in reverse order). Read logs are
summarized (latency by idle gap) and the full logs are not kept.

Writes benchmarks/results/int4_benchmark.json and the speed section of
docs/int4-experts.md. Run with browsers and VS Code closed.
"""

from __future__ import annotations

import argparse
import json
import statistics
from dataclasses import replace
from pathlib import Path

from expertrelay import REPO_ROOT
from expertrelay.bench.int4_report import upsert_section
from expertrelay.bench.phase2_baselines import run_one
from expertrelay.bench.phase4_benchmark import CACHE_CONFIG, cache_metrics, fit_cache
from expertrelay.bench.stepb_benchmark import read_log_summary
from expertrelay.benchmarking import append_benchmark_record, base_record
from expertrelay.manager.profile import collect_machine_profile
from expertrelay.paths import BENCHMARK_RESULTS_DIR, MODELS_ROOT
from expertrelay.runtime.generate import DEFAULT_RUNTIME_CONFIG, RuntimeConfig

CACHE_GB = 1.25
TIMEOUT_S = 3600
OUT = BENCHMARK_RESULTS_DIR / "int4_benchmark.json"


def setups(stores: dict[str, Path]) -> list[dict]:
    common = ["--int8-kernel", "fused", "--log-reads"]
    cached = [*common, "--io-threads", "2", "--prefill-pipelining", "--no-pin-layer0"]
    out = []
    for precision, store in stores.items():
        sd = ["--store-dir", str(store)]
        out += [
            {"id": f"{precision}_nocache", "precision": precision, "name": f"{precision}, no cache",
             "source": "unbuffered", "budget": True, "cache": False, "store": store, "args": [*common, *sd]},
            {"id": f"{precision}_cache", "precision": precision, "name": f"{precision}, cache {CACHE_GB} GB",
             "source": "cached", "budget": True, "cache": True, "store": store,
             "args": [*cached, *sd, "--no-prefetch"]},
            {"id": f"{precision}_adaptive", "precision": precision,
             "name": f"{precision}, cache {CACHE_GB} GB + adaptive prefetch",
             "source": "cached", "budget": True, "cache": True, "store": store,
             "args": [*cached, *sd, "--prefetch", "--prefetch-adaptive", "--prefetch-min-probability", "0.05"]},
        ]  # fmt: skip
    return out


def disk_per_token(run: dict) -> dict:
    decode = [s for p in run["prompts"] for s in p["steps"][1:]]
    n = len(decode)
    return {
        "device_mb_per_token": statistics.fmean(s["device_bytes"] for s in decode) / 1e6,
        "expert_mb_per_token": sum(s["expert_bytes"] + s["prefetch_bytes"] for s in decode) / n / 1e6,
    }


def agreement(results: list[dict]) -> dict:
    ok = [r for r in results if r["status"] == "ok"]
    out = {}
    for r in ok:
        ref = next((x for x in ok if x["id"] == f"{r['precision']}_nocache"), None)
        toks = [p["generated_ids"] for p in r["run"]["prompts"]]
        out[f"{r['id']}#{r['round']}"] = (
            toks == [p["generated_ids"] for p in ref["run"]["prompts"]] if ref else None
        )
    return out


def _m(runs: list[dict], sub: str, key: str) -> float:
    return statistics.fmean(r[sub][key] for r in runs)


def format_markdown(record: dict) -> str:
    res = [r for r in record["results"] if r["status"] == "ok"]
    free = record["machine"]["memory"]["available_bytes"] / 1e9
    lines = [
        "## Speed: int8 vs int4",
        "",
        f"Generated by `python -m expertrelay.bench.int4_benchmark` at {record['timestamp']} "
        f"(commit {record['git_commit'][:7]}{', dirty tree' if record['git_dirty'] else ''}) from "
        "`benchmarks/results/int4_benchmark.json`. Do not edit by hand.",
        "",
        f"Phase 2 prompts (4 x 32 tokens, greedy), base model, fused kernel, 2 I/O threads, pipelined prefill; "
        f"cache {CACHE_GB} GB for both precisions. Each setup ran twice; means. RAM free at the start: "
        f"{free:.2f} GB. Disk MB per token: expert bytes the runtime read (demand + prefetch); device MB: what "
        "the OS counted for all processes.",
        "",
        "| setup | tok/s (runs) | first token, s | compute, s/token | blocked on reads, s/token | "
        "expert MB read / token | device MB / token | experts in cache | hit rate | peak RAM MB |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for s in record["config"]["setups"]:
        runs = [r for r in res if r["id"] == s["id"]]
        if not runs:
            lines.append(f"| {s['name']} | failed |" + " |" * 8)
            continue
        each = ", ".join("{:.3f}".format(r["metrics"]["decode_tokens_per_s"]) for r in runs)
        slots = runs[0]["run"]["load"].get("cache", {}).get("slots", "-")
        lines.append(
            f"| {s['name']} | **{_m(runs, 'metrics', 'decode_tokens_per_s'):.3f}** ({each}) | "
            f"{_m(runs, 'metrics', 'time_to_first_token_mean_s'):.1f} | "
            f"{_m(runs, 'metrics', 'decode_compute_s_per_token'):.3f} | "
            f"{_m(runs, 'metrics', 'decode_expert_read_s_per_token'):.3f} | "
            f"{_m(runs, 'disk', 'expert_mb_per_token'):.0f} | {_m(runs, 'disk', 'device_mb_per_token'):.0f} | "
            f"{slots} | {_m(runs, 'cache', 'decode_hit_rate'):.1%} | "
            f"{statistics.fmean(r['peak_rss_mb_polled'] for r in runs):.0f} |"
        )
    same = record["agreement"]
    lines += [
        "",
        "Tokens identical to the same precision's no-cache run: "
        + ", ".join(f"{k}: {v}" for k, v in same.items())
        + ".",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--int4-store", type=Path, default=None)
    ap.add_argument("--rounds", type=int, default=2)
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()
    if args.report:
        print(
            f"wrote {upsert_section('speed', format_markdown(json.loads(OUT.read_text(encoding='utf-8'))[-1]))}"
        )
        return
    if args.int4_store is None:
        ap.error("--int4-store is required (the group size with the better quality)")

    stores = {"int8": MODELS_ROOT / "qwen1.5-moe-a2.7b-int8", "int4": args.int4_store.resolve()}
    rt_cache = RuntimeConfig.load(CACHE_CONFIG)
    plan = setups(stores)
    prompts = json.loads(RuntimeConfig.load(DEFAULT_RUNTIME_CONFIG).prompts_file.read_text(encoding="utf-8"))
    record = base_record(
        label="int8 vs int4 experts: speed",
        seed=0,
        model={name: p.relative_to(REPO_ROOT).as_posix() for name, p in stores.items()},
        config={
            "prompts": prompts["prompts"],
            "cache_gb": CACHE_GB,
            "rounds": args.rounds,
            "setups": [
                {k: (v.relative_to(REPO_ROOT).as_posix() if isinstance(v, Path) else v) for k, v in s.items()}
                for s in plan
            ],  # fmt: skip
        },
        machine=collect_machine_profile(measure_disk=False),
    )
    results = []
    for rnd in range(args.rounds):
        for s in plan if rnd % 2 == 0 else plan[::-1]:
            s = dict(s)
            fit = None
            if s["cache"]:
                fit = fit_cache(replace(rt_cache, store_dir=s["store"]), CACHE_GB)
                s["args"] = [*s["args"], "--cache-gb", f"{fit['used_gb']:.9f}"]
            r = run_one(s, CACHE_CONFIG if s["cache"] else DEFAULT_RUNTIME_CONFIG, TIMEOUT_S)
            r["round"], r["cache_fit"] = rnd, fit
            r["store"] = Path(s["store"]).name
            if r["status"] == "ok":
                r["cache"] = cache_metrics(r["run"])
                r["disk"] = disk_per_token(r["run"])
                r["read_log_summary"] = read_log_summary(r["run"])
                r["run"]["read_log"] = None  # summarized above; the full log would make the file huge
            results.append(r)
    record["results"] = results
    record["agreement"] = agreement(results)
    append_benchmark_record(OUT, record)
    print(f"saved {OUT}; wrote {upsert_section('speed', format_markdown(record))}")


if __name__ == "__main__":
    main()
