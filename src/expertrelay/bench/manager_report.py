"""docs/manager.md: Phase 6, the Manager (--auto), generated from
benchmarks/results/manager_validation.json.

    python -m expertrelay.bench.manager_report
"""

from __future__ import annotations

import json
import statistics

from expertrelay import REPO_ROOT
from expertrelay.bench.manager_validation import MODES, OUT, auto_mode

DOC = REPO_ROOT / "docs" / "manager.md"

HEAD = """# The Manager: --auto (Phase 6)

Generated by `python -m expertrelay.bench.manager_report` from
`benchmarks/results/manager_validation.json`. Do not edit by hand.

`python -m expertrelay.runtime.generate --auto ...` measures the machine
and configures the runtime itself; nothing is set by hand.

**Startup probe** (`runtime/auto.py`, `manager/probe.py`): the machine
profile (free RAM before anything is loaded, CPU cores, accelerator), the
time per expert read on the actual store with 1 and 2 reads in flight (48
reads each), and the compute time per layer over 4 decode tokens of a
fixed probe prompt (reads excluded). The probe's tokens are discarded and
it bypasses the cache, so it warms nothing the run then uses.

**Decisions** (`manager/policy.py`, each saved with its reason in every
run's record and printed at startup):

| setting | rule |
|---|---|
| cache size | free RAM - the rest of the process (resident weights, KV cache, scratch) - a safety margin of max(512 MiB, 5% of RAM), capped by the memory budget and by the whole store; no cache below the minimum it can run with |
| I/O threads | 2 if two reads in flight gave >= 1.10x the throughput of one, else 1 |
| prefetch | reads that fit in the per-layer window (MoE compute of this layer + attention of the next) / time per read: >= 8 fixed top-8; otherwise adaptive if the top guess's expected saving (P(used) x part of a read hidden) >= the cost of a wrong read ((1 - P) x one read), else off |
| pin layer 0 | only if its experts would be <= 25% of the cache |
| backend | Ascend NPU -> MindSpore, else numpy (`manager/backend_selection.py`) |
| precision | int8; GPTQ int4 experts only with `--fast`, which prints their measured quality cost |

**Live memory budget:** `--budget-file FILE` (a number of GB). When the
file's contents change, the cache is resized between tokens by the same
rule (`LiveBudget`, `CachedExpertSource.resize`); below its minimum the
cache shrinks to the smallest size it can run with. Tests check the
tokens stay identical through a resize (`tests/test_runtime_auto.py`).
"""


def _src(r: dict) -> str:
    dirty = ", dirty tree" if r["git_dirty"] else ""
    return f"From `benchmarks/results/manager_validation.json`, {r['timestamp']} (commit {r['git_commit'][:7]}{dirty})."


def decisions_section(r: dict) -> str:
    lines = ["## What --auto decided, and why", ""]
    for regime, kernel in r["config"]["regimes"].items():
        runs = [x for x in r["results"] if x["id"] == f"{regime}_auto"]
        lines += [f"### {regime} compute ({kernel} kernel)", ""]
        for x in runs:
            m, i = x["run"]["manager"], x["run"]["manager"]["inputs"]
            lines += [
                f"Run {x['round'] + 1}: {i['free_ram_bytes'] / 1e9:.2f} GB free at start; startup (profile, probes, "
                f"decisions) took {x['run']['load']['manager_seconds']:.1f} s.",
                "",
                *[f"- **{k}**: {v}" for k, v in m["reasons"].items()],
                "",
            ]
    return "\n".join(lines)


def _m(runs: list[dict], sub: str, key: str) -> float:
    return statistics.fmean(x[sub][key] for x in runs)


def validation_section(r: dict) -> str:
    lines = [
        "## Validation: --auto vs every hand-set configuration",
        "",
        _src(r),
        "",
        "Chat model (int8), Phase 2 prompts in the Chat template (4 x 32 tokens, greedy). Two compute regimes: "
        "fast (fused int8 kernel, ~0.1 s compute per token) and slow (the old blocked numpy kernel, ~1 s). "
        f"Hand-set configurations use a {r['config']['cache_gb']} GB cache (lowered if RAM is short at a run's "
        "start), 2 I/O threads, no pinning; --auto chooses everything itself, including its cache size from the "
        f"RAM free at its start. Each setup ran {r['config']['rounds']} times (second round in reverse order); "
        "means, single runs in brackets.",
        "",
        "Session: "
        + "; ".join(
            f"session {s['index']} at {s['timestamp']}, {s['ram_available_bytes'] / 1e9:.2f} GB RAM free, "
            f"{len(s['runs'])} runs"
            for s in r["sessions"]
        )
        + (". Interrupted and finished in a second session." if r["interrupted"] else "."),
        "",
    ]
    for regime, kernel in r["config"]["regimes"].items():
        sc = r["score"][regime]
        lines += [
            f"### {regime} compute ({kernel} kernel)",
            "",
            "| setup | mode | tok/s (runs) | first token, s | compute, s/token | blocked, s/token | expert MB / token "
            "| hit rate | experts in cache (runs) | peak RAM MB |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for kind in ("auto", *MODES):
            runs = [x for x in r["results"] if x["id"] == f"{regime}_{kind}"]
            mode = ", ".join(sorted({auto_mode(x["run"]) for x in runs})) if kind == "auto" else MODES[kind]
            name = "**--auto**" if kind == "auto" else runs[0]["name"]
            cached = [x for x in runs if isinstance(x.get("cache"), dict)]
            hit = f"{_m(cached, 'cache', 'decode_hit_rate'):.1%}" if cached else "-"
            slots = " / ".join(str(x["run"]["load"].get("cache", {}).get("slots", "-")) for x in runs)
            each = ", ".join(f"{x['metrics']['decode_tokens_per_s']:.3f}" for x in runs)
            lines.append(
                f"| {name} | {mode} | **{_m(runs, 'metrics', 'decode_tokens_per_s'):.3f}** ({each}) | "
                f"{_m(runs, 'metrics', 'time_to_first_token_mean_s'):.1f} | "
                f"{_m(runs, 'metrics', 'decode_compute_s_per_token'):.3f} | "
                f"{_m(runs, 'metrics', 'decode_expert_read_s_per_token'):.3f} | "
                f"{_m(runs, 'disk', 'expert_mb_per_token'):.0f} | {hit} | {slots} | "
                f"{statistics.fmean(x['peak_rss_mb_polled'] for x in runs):.0f} |"
            )
        lowered = [
            x for x in r["results"] if x["regime"] == regime and (x.get("cache_fit") or {}).get("lowered")
        ]
        lines += [
            "",
            f"Best hand-set: **{MODES[sc['best_hand_set']]}** ({sc['mean_tokens_per_s'][sc['best_hand_set']]:.3f} "
            f"tok/s). --auto chose **{', '.join(sc['auto_modes'])}**: "
            f"{'matches' if sc['picked_best'] else 'does not match'} the best hand-set mode (the rule fixed before "
            f"the run). --auto / best = **{sc['auto_over_best']:.3f}**.",
        ]
        if lowered:
            lines += [
                "",
                "Hand-set cache lowered for lack of free RAM at the run's start: "
                + ", ".join(f"{x['id']}#{x['round']} ({x['cache_fit']['slots']} experts)" for x in lowered)
                + ".",
            ]
        lines.append("")
    same = r["agreement"]
    lines.append(
        f"Tokens identical to the regime's no-cache run: {sum(1 for v in same.values() if v)} of {len(same)} runs."
    )
    return "\n".join(lines)


def write() -> None:
    r = json.loads(OUT.read_text(encoding="utf-8"))[-1]
    parts = [HEAD, decisions_section(r), validation_section(r)]
    DOC.write_text("\n\n".join(p.rstrip("\n") for p in parts) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write()
    print(f"wrote {DOC}")
