from __future__ import annotations

import json
import statistics

from expertrelay import REPO_ROOT
from expertrelay.bench.quantization_quality import PASS_CATEGORY, PASS_OVERALL
from expertrelay.paths import BENCHMARK_RESULTS_DIR

DOC = REPO_ROOT / "docs" / "gptq-int4.md"
STORES = ("qwen1.5-moe-a2.7b-chat-int4g128-gptq", "qwen1.5-moe-a2.7b-chat-int4g128-rtn")
NAMES = {"int8": "int8", "int4_rtn_g128": "int4 RTN g128", "int4_gptq_g128": "int4 GPTQ g128"}

HEAD = """# GPTQ int4 experts on the Chat model (Step B3)

Generated by `python -m expertrelay.bench.gptq_report` from the results
files named in each section. Do not edit by hand.

**Question.** Step B2's plain round-to-nearest (RTN) int4 experts read half
the bytes per token but failed the quality bar. Does calibrated int4
(GPTQ) pass it, at the same speed benefit?

**Pass rule, fixed before any result:** top-1 next-token agreement with the
original bf16 Chat model >= 96% overall AND >= 90% in every category.

**What is compared.** Three stores of Qwen1.5-MoE-A2.7B-Chat (commit
ec052fda) that differ ONLY in the routed experts; everything resident
(attention, shared expert, router, norms, embedding, lm_head) is the int8
Chat store's, hard-linked:
- **int8**: per-row absmax int8 experts (the existing Chat store).
- **int4 GPTQ g128**: the routed experts of the official GPTQ release
  [Qwen/Qwen1.5-MoE-A2.7B-Chat-GPTQ-Int4](https://huggingface.co/Qwen/Qwen1.5-MoE-A2.7B-Chat-GPTQ-Int4)
  @ 81b132a (4 bits, group 128, symmetric, desc_act off), re-packed into
  our record format without changing a value (`store/gptq.py`). The
  release also quantizes attention and the shared expert; those are NOT
  used here (they stay int8), so this measures GPTQ experts, not the whole
  GPTQ model.
- **int4 RTN g128**: round-to-nearest from the bf16 Chat weights on
  GPTQ's own grid (values -8..7, scale = 2 max|w| / 15, group 128;
  `store/int4.py`), so RTN and GPTQ have identical codes, scales and
  record size, and differ only by GPTQ's error compensation.

**Method and sources.**
- GPTQ: E. Frantar, S. Ashkboos, T. Hoefler, D. Alistarh, "GPTQ: Accurate
  Post-Training Quantization for Generative Pre-trained Transformers",
  ICLR 2023, arXiv:2210.17323. The quantization grid reproduced for RTN is
  the reference implementation's `Quantizer.find_params` / `quantize`
  (github.com/IST-DASLab/gptq, `quant.py`).
- The release: Qwen team, Qwen1.5-MoE-A2.7B-Chat-GPTQ-Int4, Hugging Face
  model card (introduced in the Qwen1.5-MoE blog post,
  https://qwenlm.github.io/blog/qwen-moe/). The card does not name the
  quantization tool.
- Checkpoint format: AutoGPTQ's "gptq" (v1) layout, in which zero points
  are stored minus one (`pack`: `zeros -= 1`; dequantization:
  `zeros = zeros + 1`; github.com/AutoGPTQ/AutoGPTQ,
  `auto_gptq/nn_modules/qlinear/qlinear_cuda_old.py`). In this release
  every zero point is 8, which `store/gptq.py` checks for every group of
  every expert, so the runtime's fused int4 kernel (value = nibble - 8,
  times the group scale) runs GPTQ weights unchanged.
- Both downloads were checked file by file against the Hub's hashes
  (`benchmarks/results/checkpoint_verification.json`).
"""


def _last(name: str) -> dict | None:
    path = BENCHMARK_RESULTS_DIR / name
    return json.loads(path.read_text(encoding="utf-8"))[-1] if path.exists() else None


def _src(record: dict, file: str) -> str:
    dirty = ", dirty tree" if record["git_dirty"] else ""
    return (
        f"From `benchmarks/results/{file}`, {record['timestamp']} (commit {record['git_commit'][:7]}{dirty})."
    )


def stores_section() -> str:
    records = json.loads((BENCHMARK_RESULTS_DIR / "int4_store_build.json").read_text(encoding="utf-8"))
    latest = {r["summary"]["store"]: r for r in records if r["summary"]["store"] in STORES}
    rows = []
    int8 = None
    for store in STORES:
        r = latest[store]
        s, q = r["summary"], r["summary"]["quant_error"]
        int8 = s["int8_for_comparison"]
        rows.append(
            f"| {store} | {r['config']['quantizer']} | {s['record_size']:,} ({s['record_size'] / int8['record_size']:.1%}) | "
            f"{s['experts_bin_bytes'] / 1e9:.2f} | {s['records_verified']} / {len(s['bad_records'])} | "
            f"{q['rel_fro_error_mean']:.2%} | {q['rel_fro_error_max']:.2%} | {q['max_abs_error_over_scale']:.2f} |"
        )
    iq = int8["quant_error"]
    return "\n".join(
        [
            "## The stores",
            "",
            "From `benchmarks/results/int4_store_build.json` (latest record per store). Error = "
            "||W - W_hat|| / ||W|| per expert against the bf16 Chat weights; max error / step > 0.5 means weights "
            "moved further than rounding would move them (GPTQ's error compensation does that on purpose).",
            "",
            "| store | quantizer | record bytes (vs int8) | experts.bin GB | records verified / bad | "
            "mean error | max error | max error / step |",
            "|---|---|---|---|---|---|---|---|",
            *rows,
            f"| int8 Chat (reference) | per-row absmax | {int8['record_size']:,} | {int8['experts_bin_bytes'] / 1e9:.2f} "
            f"| - | {iq['rel_fro_error_mean']:.2%} | {iq['rel_fro_error_max']:.2%} | {iq['max_abs_error_over_scale']:.2f} |",
            "",
            "GPTQ's weights are further from bf16 than RTN's: GPTQ minimizes the error of each layer's OUTPUT on "
            "calibration data, not the weight error.",
        ]
    )


def conversion_section() -> str:
    r = _last("gptq_conversion_check.json")
    s = r["summary"]
    return "\n".join(
        [
            "## Conversion check",
            "",
            _src(r, "gptq_conversion_check.json"),
            "",
            f"The GPTQ store's records (as the runtime reads them) vs the release's raw tensors dequantized by an "
            f"independent implementation of the documented formula W[o,i] = (q[i,o] - (z[g_idx[i],o] + 1)) * "
            f"s[g_idx[i],o] (general zero points and g_idx): **{s['matrices_checked']} matrices of "
            f"{s['experts_checked']} sampled experts, all bit-identical: {s['all_identical']}**. Unit tests "
            "(`tests/test_store_gptq.py`) check the same formula, the refusals (other zero points, desc_act order, "
            "bias), and both int4 kernels against a float64 reference over the full -8..7 range.",
        ]
    )


def quality_section() -> str:
    r = _last("gptq_quality.json")
    a = r["analysis"]
    names = list(a["by_precision"])
    cats = [c for c in a["by_precision"][names[0]]["by_category"] if not c.startswith("phase2_")]
    lines = [
        "## Quality vs bf16 Chat",
        "",
        _src(r, "gptq_quality.json"),
        "",
        f"{a['prompts']} prompts (4 from Phase 2 + 4 per category), in the Chat template; each continued by the "
        f"int8 store for 32 tokens, and every model scored on the same {a['positions']} positions (teacher "
        "forcing) against bf16's next token. Top-1 = our most likely next token equals bf16's; KL(bf16 || ours) "
        "in nats per position. Generated = the 32 continuation positions only.",
        "",
        f"Pass rule: overall >= {PASS_OVERALL:.0%} and every category >= {PASS_CATEGORY:.0%}.",
        "",
        "| experts | top-1, all | top-1, generated | mean KL | max KL | worst category | verdict |",
        "|---|---|---|---|---|---|---|",
    ]
    for n in names:
        o, v = a["by_precision"][n]["overall"], a["verdict"][n]
        lines.append(
            f"| {NAMES.get(n, n)} | **{o['top1_agreement']:.1%}** | {o['top1_agreement_generated']:.1%} | "
            f"{o['kl_mean']:.4f} | {o['kl_max']:.3f} | {v['worst_category']} {v['worst_category_top1']:.1%} | "
            f"**{'PASS' if v['pass'] else 'FAIL'}** |"
        )
    lines += [
        "",
        "Per category, top-1 / mean KL:",
        "",
        "| category | " + " | ".join(NAMES.get(n, n) for n in names) + " |",
    ]
    lines.append("|---|" + "---|" * len(names))
    for c in cats:
        cells = [
            f"{a['by_precision'][n]['by_category'][c]['top1_agreement']:.1%} / "
            f"{a['by_precision'][n]['by_category'][c]['kl_mean']:.4f}"
            for n in names
        ]
        lines.append(f"| {c} | " + " | ".join(cells) + " |")
    lines += ["", "Arabic (ar_msa, ar_gulf and Phase 2's Arabic prompt):", ""]
    lines += ["| experts | top-1, all | top-1, generated | mean KL | max KL |", "|---|---|---|---|---|"]
    for n in names:
        x = a["by_precision"][n]["arabic"]
        lines.append(
            f"| {NAMES.get(n, n)} | {x['top1_agreement']:.1%} | {x['top1_agreement_generated']:.1%} | "
            f"{x['kl_mean']:.4f} | {x['kl_max']:.3f} |"
        )
    return "\n".join(lines)


def _m(runs: list[dict], sub: str, key: str) -> float:
    return statistics.fmean(r[sub][key] for r in runs)


def speed_section() -> str:
    r = _last("gptq_benchmark.json")
    if r is None:
        return "## Speed\n\nPending: `python -m expertrelay.bench.gptq_benchmark` has not been run yet."
    res = r["results"]
    lines = [
        "## Speed",
        "",
        _src(r, "gptq_benchmark.json"),
        "",
        f"Phase 2 prompts in the Chat template (4 x 32 tokens, greedy), fused kernels, 2 I/O threads, pipelined "
        f"prefill, cache {r['config']['cache_gb']} GB for both precisions; each setup ran {r['config']['rounds']} "
        "times (second round in reverse order); means, single runs in brackets. Each precision's adaptive "
        "prefetch uses a calibration fitted on its own store's traces. Expert MB = bytes the runtime read "
        "(demand + prefetch); compute and blocked time per decode token.",
        "",
        "Sessions (browsers and VS Code closed): "
        + "; ".join(
            f"session {s['index']} at {s['timestamp']}, {s['ram_available_bytes'] / 1e9:.2f} GB RAM free, "
            f"{len(s['runs'])} runs"
            for s in r["sessions"]
        )
        + (". The run was interrupted and finished in a second session." if r["interrupted"] else ".")
        + (f" Failed attempts redone: {len(r['failed_attempts'])}." if r["failed_attempts"] else ""),
        "",
        "| setup | tok/s (runs) | first token, s | compute, s/token | blocked, s/token | expert MB / token | "
        "experts in cache | hit rate | peak RAM MB |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in r["config"]["setups"]:
        runs = [x for x in res if x["id"] == s["id"]]
        each = ", ".join(f"{x['metrics']['decode_tokens_per_s']:.3f}" for x in runs)
        # per run: fit_cache lowers a run's cache when RAM is short at its start
        slots = " / ".join(str(x["run"]["load"].get("cache", {}).get("slots", "-")) for x in runs)
        hit = f"{_m(runs, 'cache', 'decode_hit_rate'):.1%}" if s["cache"] else "-"
        lines.append(
            f"| {s['name']} | **{_m(runs, 'metrics', 'decode_tokens_per_s'):.3f}** ({each}) | "
            f"{_m(runs, 'metrics', 'time_to_first_token_mean_s'):.1f} | "
            f"{_m(runs, 'metrics', 'decode_compute_s_per_token'):.3f} | "
            f"{_m(runs, 'metrics', 'decode_expert_read_s_per_token'):.3f} | "
            f"{_m(runs, 'disk', 'expert_mb_per_token'):.0f} | {slots} | {hit} | "
            f"{statistics.fmean(x['peak_rss_mb_polled'] for x in runs):.0f} |"
        )
    same = r["agreement"]
    lowered = [f"{x['id']}#{x['round']}" for x in res if (x.get("cache_fit") or {}).get("lowered")]
    if lowered:
        lines += [
            "",
            f"Cache lowered below {r['config']['cache_gb']} GB because RAM was short at the run's start: "
            + ", ".join(
                f"{k} ({x['cache_fit']['slots']} experts, {x['cache_fit']['used_gb']:.3f} GB)"
                for k, x in zip(
                    lowered, [x for x in res if (x.get("cache_fit") or {}).get("lowered")], strict=True
                )
            )
            + ". Experts in cache are listed per run.",
        ]
    lines += [
        "",
        f"Tokens identical to the same precision's no-cache run: {sum(1 for v in same.values() if v)} of "
        f"{len(same)} runs ({', '.join(k for k, v in same.items() if not v) or 'all identical'}).",
    ]
    return "\n".join(lines)


def write() -> None:
    parts = [HEAD, stores_section(), conversion_section(), quality_section(), speed_section()]
    DOC.write_text("\n\n".join(p.rstrip("\n") for p in parts) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write()
    print(f"wrote {DOC}")
